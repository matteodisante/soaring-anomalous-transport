#!/usr/bin/env python3
r"""Map generated thesis inputs to their producers and rebuild stages.

Reads static output declarations, generated TeX headers, macro uses and
``configs/rebuild.yaml`` without executing reporting scripts. Writes
``docs/guide/provenance.md``. ``--check`` validates declarations and required
inputs without rewriting the index. This identifies producers; completed-run
freshness is checked separately by ``scripts/rebuild_thesis.py``.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
import warnings
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
THESIS = ROOT / "thesis"
GENERATED = THESIS / "generated"
OUT_MD = ROOT / "docs" / "guide" / "provenance.md"

# The thesis sources that may quote a macro or include a figure.
SOURCES = sorted(
    [
        *THESIS.glob("sections/*.tex"),
        *THESIS.glob("appendices/**/*.tex"),
        THESIS / "main.tex",
    ]
)

# A script names what it writes by assigning the path to an OUT_* constant, which is how
# this repo has always spelled an output. Requiring the name as well as the path is what
# separates writing from reading: audit_msd_report.py also names msd_curve.csv, as
# CURVE_CSV, because it consumes what generate_msd_figure.py produced. Matching a bare
# filename would read a docstring mention as authorship -- three scripts name
# altitude_noise.pdf in prose and one writes it.
_WRITES = re.compile(
    r'OUT\w*\s*=\s*ROOT\s*/\s*"thesis"\s*/\s*"generated"\s*/\s*"([^"]+)"'
)
_HEADER = re.compile(r"^%\s*Generated by\s+(\S+\.py)", re.M)
_MACRO = re.compile(r"\\newcommand\{\\(\w+)\}")
_FIGURE = re.compile(r"\\includegraphics(?:\[[^\]]*\])?\{generated/([^}]+)\}")
_INPUT = re.compile(r"\\(?:input|InputIfFileExists)\{generated/([^}]+)\}")
_STEP = re.compile(r'^step "(\d+)/\d+\s+([^"]*)"|^"\$PY"\s+(\S+\.py)', re.M)


def declared_outputs(source: str) -> set[str]:
    """Read static output contracts without importing or executing reporting code.

    A literal ``GENERATED_OUTPUTS`` tuple lists basenames for scripts that construct
    paths dynamically, for example one figure per discipline. A prose mention or
    a path read as an input is not an authorship declaration.
    """
    names = set(_WRITES.findall(source))
    with warnings.catch_warnings():
        # Older scientific docstrings contain literal LaTeX backslashes. Parsing
        # metadata must not re-emit their unrelated invalid-escape warnings.
        warnings.simplefilter("ignore", SyntaxWarning)
        tree = ast.parse(source)
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        if not any(
            isinstance(target, ast.Name) and target.id == "GENERATED_OUTPUTS"
            for target in node.targets
        ):
            continue
        declared = ast.literal_eval(node.value)
        if not isinstance(declared, tuple) or not all(
            isinstance(name, str) and Path(name).name == name for name in declared
        ):
            raise ValueError("GENERATED_OUTPUTS must be a literal tuple of basenames")
        names.update(declared)
    return names


def writers() -> dict[str, str]:
    """Generated filename -> the script whose source declares it as an output."""
    found: dict[str, str] = {}
    for script in sorted(ROOT.glob("scripts/**/*.py")):
        rel = script.relative_to(ROOT).as_posix()
        for name in declared_outputs(script.read_text()):
            found.setdefault(name, rel)
    return found


def steps() -> dict[str, int]:
    """Script -> its first stage number in the canonical rebuild plan."""
    import yaml

    out: dict[str, int] = {}
    plan = yaml.safe_load((ROOT / "configs/rebuild.yaml").read_text())
    for number, stage in enumerate(plan["stages"], 1):
        out.setdefault(stage["script"], number)
    return out


def hook_scripts() -> set[str]:
    """Read the reporting scripts also invoked by the pre-commit hook."""
    text = (ROOT / ".githooks" / "pre-commit").read_text()
    return set(re.findall(r"scripts/[\w/]+\.py", text))


def defined_macros() -> dict[str, str]:
    """Macro name -> the generated file that defines it."""
    out: dict[str, str] = {}
    for path in sorted(GENERATED.glob("*.tex")):
        for name in _MACRO.findall(path.read_text()):
            out[name] = path.name
    return out


def used_in(defined: set[str]) -> tuple[dict[str, set[str]], dict[str, set[str]]]:
    r"""``(macros, figures)``, each mapping a name to the thesis files that use it.

    Every control sequence in the sources is collected and intersected with the names
    the generators define, rather than filtered by an expected prefix. A family added
    under a new prefix is picked up with no change here, and ``\DataCascadeParaRows``
    -- which matches no ``Stat``/``Preproc`` convention, and is quoted in Ch. 2 -- is
    not reported missing.
    """
    macros: dict[str, set[str]] = defaultdict(set)
    figures: dict[str, set[str]] = defaultdict(set)
    pending = list(SOURCES)
    seen: set[Path] = set()
    while pending:
        source = pending.pop()
        if source in seen:
            continue
        seen.add(source)
        lines = []
        for line in source.read_text().splitlines():
            for index, char in enumerate(line):
                if char == "%":
                    escapes = len(line[:index]) - len(line[:index].rstrip("\\"))
                    if escapes % 2 == 0:
                        line = line[:index]
                        break
            lines.append(line)
        text = "\n".join(lines)
        # A definition's name is not a use. References inside its body remain
        # relevant static dependencies; this scan does not expand TeX macros.
        text = re.sub(
            r"\\(?:newcommand|renewcommand|providecommand)\s*\{\\[A-Za-z]+\}",
            "",
            text,
        )
        label = source.relative_to(THESIS).as_posix()
        for name in set(re.findall(r"\\(\w+)", text)) & defined:
            macros[name].add(label)
        for figure in _FIGURE.findall(text):
            filename = figure if Path(figure).suffix else f"{figure}.pdf"
            figures[filename].add(label)
        for fragment in _INPUT.findall(text):
            filename = fragment if Path(fragment).suffix else f"{fragment}.tex"
            figures[filename].add(label)
            included = THESIS / "generated" / filename
            if included.is_file():
                pending.append(included)
    return macros, figures


def collect() -> tuple[dict, dict, list[str]]:
    """``(artefacts, macros, problems)``, from one pass over the repository."""
    produced_by = writers()
    step_of = steps()
    by_hook = hook_scripts()
    defines = defined_macros()
    used, figures = used_in(set(defines))
    problems: list[str] = []

    artefacts: dict[str, dict] = {}
    for path in sorted(GENERATED.glob("*")):
        if path.suffix not in (".tex", ".pdf", ".csv", ".json"):
            continue
        # A .tex declares its author in its first line; a .pdf cannot, so for a figure
        # the OUT_* assignment is the only signal there is. Where both exist they must
        # agree, and that disagreement is what this catches.
        if path.suffix == ".tex":
            match = _HEADER.search(path.read_text())
            script = match.group(1) if match else None
            if script is None:
                problems.append(f"{path.name}: no '% Generated by' header")
            built = produced_by.get(path.name)
            if script and built and built != script:
                problems.append(
                    f"{path.name}: header says {script}, {built} declares the output"
                )
        else:
            script = produced_by.get(path.name)
            if script is None:
                problems.append(f"{path.name}: no script declares this output")
        artefacts[path.name] = {
            "script": script,
            "step": step_of.get(script or ""),
            "hook": script in by_hook,
            # LaTeX includes a figure without its extension.
            "used_in": sorted(figures.get(path.name, ())),
        }

    # Check included assets independently of LaTeX's behaviour. Some inclusions
    # have a placeholder fallback and others fail directly. This index checks
    # presence; the rebuild separately verifies every required output's freshness.
    on_disk = {path.name for path in GENERATED.glob("*")}
    for name, places in sorted(figures.items()):
        if name in on_disk or f"{name}.pdf" in on_disk or f"{name}.tex" in on_disk:
            continue
        where = ", ".join(places)
        problems.append(
            f"{name}: included by {where} but not in thesis/generated/ -- "
            "the build will show a placeholder box in its place"
        )

    macros = {
        name: {"file": source, "used_in": sorted(used.get(name, ()))}
        for name, source in defines.items()
    }
    # Record both literal file inclusions and uses of the macros they define.
    for info in macros.values():
        entry = artefacts.get(info["file"])
        if entry is not None:
            entry["used_in"] = sorted(set(entry["used_in"]) | set(info["used_in"]))

    return artefacts, macros, problems


def family(name: str) -> str:
    """``StatVarParaAlphaOrderOne`` -> ``StatVar``, the grouping the thesis reads by."""
    if name.startswith("Preproc"):
        return "Preproc"
    match = re.match(r"(Stat[A-Z][a-z]+)", name)
    return match.group(1) if match else name


def _repo_blob() -> str:
    """The base URL for linking a source file, from ``mkdocs.yml``'s ``repo_url``.

    Read rather than repeated: the site already declares where the repository is, and a
    second copy here would be one more thing to keep in step. A relative path cannot be
    used -- the scripts are not part of the documentation tree, and ``mkdocs --strict``
    fails a link that leaves it.
    """
    text = (ROOT / "mkdocs.yml").read_text()
    match = re.search(r"^repo_url:\s*(\S+)", text, re.M)
    return f"{match.group(1).rstrip('/')}/blob/main" if match else ""


def _link(script: str | None) -> str:
    """A script as a link into the repository, or an em dash if it is unknown."""
    return f"[`{script}`]({_repo_blob()}/{script})" if script else "—"


def _when(info: dict) -> str:
    """How an artefact gets rebuilt: a chain step, the commit hook, or by hand."""
    if info["step"]:
        return f"step {info['step']}"
    return "pre-commit hook" if info["hook"] else "run by hand"


def render(artefacts: dict, macros: dict) -> str:
    """The page: the files, then the macro families, then what is written unused."""
    lines = [
        "<!-- Generated by scripts/reporting/checks/generate_provenance.py. "
        "Do not edit. -->",
        "# Where each number and figure comes from",
        "",
        "Each generated statistic, table, figure and audit report is linked to its",
        "producing script. Empirical analyses read the archive; schematics encode",
        "their stated mathematical construction. This index leads from an artefact",
        "back to the code that declares it. Rebuild stages come from",
        "`configs/rebuild.yaml`; this page is regenerated by `generate_provenance.py`.",
        "The index does not certify data freshness: use the completed run manifest",
        "described in [Rebuilding the thesis](rebuilding.md).",
        "",
        "## The generated files",
        "",
        "| file | written by | rebuilt | used in |",
        "|---|---|---|---|",
    ]
    for name, info in sorted(artefacts.items()):
        used = ", ".join(f"`{u}`" for u in info["used_in"]) or "—"
        lines.append(f"| `{name}` | {_link(info['script'])} | {_when(info)} | {used} |")

    grouped: dict[tuple[str, str], list[str]] = defaultdict(list)
    for name, info in macros.items():
        grouped[family(name), info["file"]].append(name)

    lines += [
        "",
        "## The macro families",
        "",
        "Rows separate a naming family by its actual defining file and producer.",
        "The count is the number of family members in that file; references include",
        "literal uses in authored sources and included generated tables, excluding",
        "comments and definition names. This static scan does not expand TeX macros.",
        "",
        "| family | file | written by | quoted in | macros |",
        "|---|---|---|---|---|",
    ]
    for (fam, source), names in sorted(grouped.items()):
        script = artefacts.get(source, {}).get("script")
        places = sorted({p for n in names for p in macros[n]["used_in"]})
        used = ", ".join(f"`{p}`" for p in places) or "**not quoted**"
        lines.append(
            f"| `\\{fam}*` | `{source}` | {_link(script)} | {used} | {len(names)} |"
        )

    lines += [
        "",
        "## Written but not quoted",
        "",
        "A generator may legitimately write more than the current draft uses: a macro",
        "dropped from the text in a revision, or one written for a section not yet",
        "drafted. They are listed so the difference stays visible, not because a macro",
        "here is wrong.",
        "",
    ]
    unquoted: dict[str, list[str]] = defaultdict(list)
    for name, info in macros.items():
        if not info["used_in"]:
            unquoted[info["file"]].append(name)
    if unquoted:
        for source, names in sorted(unquoted.items()):
            listed = ", ".join(f"`\\{n}`" for n in sorted(names))
            lines.append(f"- `{source}` — {listed}")
    else:
        lines.append("Every macro a generator writes is quoted somewhere.")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write the page, or check the chain and report what is broken."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="report broken provenance and exit non-zero; write nothing",
    )
    args = parser.parse_args()

    artefacts, macros, problems = collect()
    if args.check:
        for problem in problems:
            print(f"provenance: {problem}", file=sys.stderr)
        print(f"{len(artefacts)} files, {len(macros)} macros, {len(problems)} problems")
        return 1 if problems else 0

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(render(artefacts, macros))
    where = OUT_MD.relative_to(ROOT)
    print(f"Wrote {where}: {len(artefacts)} files, {len(macros)} macros.")
    for problem in problems:
        print(f"  note: {problem}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
